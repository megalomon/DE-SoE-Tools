def find_org_line(lines, org_target):
    target = f"org {org_target}"
    for i, line in enumerate(lines):
        if line.strip() == target:
            return i
    raise ValueError(f"Target {target} not found")

def extract_org_block(lines, start_org, end_org):
    s = find_org_line(lines, start_org)
    e = find_org_line(lines, end_org)
    return "\n".join(lines[s:e]).strip()

def extract_lines(lines, start_idx, end_idx):
    return "\n".join(lines[start_idx:end_idx]).strip()

